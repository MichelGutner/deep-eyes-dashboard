const PERMISSION_DOC = 'Permissão declarada no manifest. true = concedida pelo usuário, false = negada ou ainda não concedida.';

/** Strips array indexes and maps reporterContext to context so both share one set of docs. */
function normalize(path: string[]): string[] {
  const parts = path.filter(part => !/^\d+$/.test(part));
  if (parts[0] === 'reporterContext') parts[0] = 'context';
  return parts;
}

/** Explanation for the field at `path` (relative to metadata), or undefined when none is documented. */
export function getFieldDoc(path: string[]): string | undefined {
  const parts = normalize(path);
  if (parts.includes('permissions') && parts.length > 2) return PERMISSION_DOC;
  const candidates: string[] = [];
  for (let size = parts.length; size >= 1; size--) candidates.push(parts.slice(-size).join('.'));
  for (const key of candidates) {
    if (DOCS[key]) return DOCS[key];
  }
  return undefined;
}
